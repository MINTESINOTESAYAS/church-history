#!/usr/bin/env python3
"""Put the whole LaTeX edition into one self-contained file.

    python3 tools/single_file.py [OUTPUT]

Reads latex/main.tex, copies the code of churchhistory.sty into the preamble and replaces
every \\include{...} by the file it names.  The default output is
latex/church-history-single-file.tex.  That file needs no other file and gives the same
pages as main.tex.

Run this again after changing anything in latex/.  Do not edit the single file and the
separate files independently: the next run overwrites the single file.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LATEX = os.path.join(ROOT, 'latex')
DEFAULT_OUT = os.path.join(LATEX, 'church-history-single-file.tex')
WIDTH = 91

HEADER = """\
% The complete book in ONE LaTeX file.
%
% Nothing else is needed to compile it.  The layout commands (the code of churchhistory.sty)
% are in the preamble; the text follows in book order:
% @SUMMARY@.
%
% Compile with pdflatex (recommended), xelatex or lualatex.  Run it twice, so that the page
% numbers on the contents page are filled in.
%
% Generated by tools/single_file.py from main.tex and the files it includes."""

PREAMBLE_HEAD = """\
%% =========================================================================================
%% PREAMBLE: page layout and structural commands.  The text starts at \\begin{document}.
%% =========================================================================================
\\makeatletter"""

BODY_HEAD = """\
%% =========================================================================================
%% THE BOOK
%% ========================================================================================="""


def read(rel):
    with open(os.path.join(LATEX, rel), encoding='utf-8') as f:
        return f.read()


def banner(text):
    side = max(3, (WIDTH - 3 - len(text) - 2) // 2)
    line = '%% ' + '=' * side + ' ' + text + ' ' + '=' * side
    return line + '=' * max(0, WIDTH - len(line))


def style_code():
    """The package code as it has to appear in a document preamble."""
    lines = read('churchhistory.sty').split('\n')
    # drop the file header (comments, \NeedsTeXFormat, \ProvidesPackage) and \endinput
    k = next(i for i, ln in enumerate(lines) if ln.startswith('\\ProvidesPackage'))
    lines = [ln for ln in lines[k + 1:] if ln.strip() != '\\endinput']
    return '\n'.join(lines).strip('\n').replace('\\RequirePackage', '\\usepackage')


def describe(counts):
    words = []
    if counts.get('frontmatter'):
        words.append('front matter')
    if counts.get('parts'):
        words.append('%d part pages' % counts['parts'])
    if counts.get('chapters'):
        words.append('%d chapters' % counts['chapters'])
    if counts.get('backmatter'):
        words.append('back matter')
    return ', '.join(words)


def build():
    main = read('main.tex').split('\n')
    k = next(i for i, ln in enumerate(main) if ln.startswith('\\documentclass'))
    b = next(i for i, ln in enumerate(main) if ln.strip() == '\\begin{document}')
    if not any(ln.strip() == '\\usepackage{churchhistory}' for ln in main[k:b]):
        sys.exit('main.tex does not load churchhistory.sty; nothing to merge')

    body, counts = [], {}
    for ln in main[b:]:
        m = re.fullmatch(r'\s*\\include\{([^}]+)\}\s*', ln)
        if not m:
            if ln.strip() or (body and body[-1] != ''):       # at most one blank line in a row
                body.append(ln)
            continue
        rel = m.group(1)
        group = rel.split('/')[0]
        counts[group] = counts.get(group, 0) + 1
        if body and body[-1] != '':
            body.append('')
        body += [banner(rel + '.tex'), read(rel + '.tex').rstrip('\n'), '']

    head = [HEADER.replace('@SUMMARY@', describe(counts)), main[k], '',
            PREAMBLE_HEAD, style_code(), '\\makeatother', '', BODY_HEAD]
    return '\n'.join(head + body).rstrip('\n') + '\n', sum(counts.values())


def main():
    out = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    text, n = build()
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    print('wrote %s: %d files merged, %d lines, %d bytes'
          % (os.path.relpath(out, ROOT), n, text.count('\n'), len(text.encode('utf-8'))))


if __name__ == '__main__':
    main()
