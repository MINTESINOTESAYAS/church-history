#!/usr/bin/env python3
"""Generate the two appendices of the summary volume.

    python3 tools/summary_extras.py            # writes summary/back/chronology.tex and popes.tex
    python3 tools/summary_extras.py --check    # only reports whether the two files are up to date

chronology.tex   every \\kd{date}{event} of the 48 chapter summaries, in order of time, with the
                 chapter it comes from.  The event text is copied unchanged.  Entries of several
                 chapters that agree in date and wording are printed once.
popes.tex        the list of popes of the LaTeX edition (latex/backmatter/popes.tex), unchanged,
                 in the layout of the summary volume.
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACK = os.path.join(ROOT, 'summary', 'back')
WIDTH = 104

ORDINALS = ['', 'First', 'Second', 'Third', 'Fourth', 'Fifth', 'Sixth', 'Seventh', 'Eighth', 'Ninth',
            'Tenth', 'Eleventh', 'Twelfth', 'Thirteenth', 'Fourteenth', 'Fifteenth', 'Sixteenth',
            'Seventeenth', 'Eighteenth', 'Nineteenth', 'Twentieth', 'Twenty-first']


# ----------------------------------------------------------------------------------------------
# Chronology
# ----------------------------------------------------------------------------------------------
def braced(text, start):
    """text[start] is '{': return (content, index after the matching '}')."""
    assert text[start] == '{', text[start - 20:start + 20]
    depth, k = 0, start
    while True:
        c = text[k]
        if c == '\\':
            k += 2
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return text[start + 1:k], k + 1
        k += 1


def date_key(date):
    """Sort key of a date label: (year, kind).  kind orders labels that start in the same year:
    a century first, then the plain year, a span of years, an approximate date, a decade."""
    s = date.strip()
    circa = s.startswith('c. ')
    if circa:
        s = s[3:]
    if s.startswith('AD '):
        s = s[3:]
    sign = 1
    if s.endswith(' BC'):
        s, sign = s[:-3], -1
    m = re.fullmatch(r'(\d+)(?:st|nd|rd|th) century', s)
    if m:
        return ((int(m.group(1)) - 1) * 100, 0)
    m = re.fullmatch(r'(\d+)s', s)
    if m:
        return (int(m.group(1)), 4)
    m = re.fullmatch(r'(\d+)(--\d+)?', s)
    if not m:
        raise ValueError('date not understood: %r' % date)
    year = sign * int(m.group(1))
    if circa:
        return (year, 3)
    return (year, 2 if m.group(2) else 1)


def heading(year):
    if year < 0:
        return 'Before Christ'
    return ORDINALS[year // 100 + 1] + ' century'


def collect():
    """All \\kd entries as dicts, in the order of the chapters."""
    entries = []
    for n in range(1, 49):
        path = os.path.join(ROOT, 'summary', 'chapters', 'ch%02d.tex' % n)
        if not os.path.exists(path):
            continue
        text = open(path, encoding='utf-8').read()
        text = re.sub(r'(?m)(?<!\\)%.*$', '', text)
        for pos, m in enumerate(re.finditer(r'\\kd\s*(?=\{)', text)):
            date, k = braced(text, m.end())
            while text[k].isspace():
                k += 1
            event, k = braced(text, k)
            date = re.sub(r'\s+', ' ', date).strip()
            event = re.sub(r'\s+', ' ', event).strip()
            entries.append({'date': date, 'event': event, 'chapters': [n],
                            'key': date_key(date) + (n, pos)})
    return entries


def wrap(line, indent='  '):
    out = []
    while len(line) > WIDTH:
        cut = line.rfind(' ', 0, WIDTH + 1)
        if cut <= len(indent):
            break
        out.append(line[:cut])
        line = indent + line[cut + 1:]
    out.append(line)
    return '\n'.join(out)


def build_chronology():
    entries = sorted(collect(), key=lambda e: e['key'])
    merged = []
    for e in entries:
        twin = next((x for x in merged if x['date'] == e['date'] and x['event'] == e['event']), None)
        if twin:
            twin['chapters'] += e['chapters']
        else:
            merged.append(e)
    lines = [
        '% Generated by tools/summary_extras.py from the \\kd entries of chapters/ch01..48.tex.',
        '% Do not edit: change the chapter files and run the script again.',
        '\\backchapter{Chronology}',
        '',
        '\\noindent This chronology gathers the key dates of all forty-eight chapters in one sequence. The',
        'number in parentheses is the chapter in which the event is treated, and events of one year stand',
        'in the order of the chapters. Dates follow the book; ``c.\'\' marks a date the book gives as',
        'approximate, and a span of years stands at the year in which it begins.',
        '',
        '\\begin{chronology}',
    ]
    last_head, last_date = None, None
    for e in merged:
        head = heading(e['key'][0])
        if head != last_head:
            lines.append('')
            lines.append('\\chronhead{%s}' % head)
            last_head, last_date = head, None
        refs = ', '.join('\\chref{%d}' % c for c in e['chapters'])
        refs = ('ch.~' if len(e['chapters']) == 1 else 'chs.~') + refs
        date = e['date'].replace('AD ', '')          # the headings name the era
        if date == last_date:
            lines.append(wrap('\\chronmore{%s}{%s}' % (e['event'], refs)))
        else:
            lines.append(wrap('\\chron{%s}{%s}{%s}' % (date, e['event'], refs)))
        last_date = date
    lines += ['\\end{chronology}', '']
    return '\n'.join(lines), len(entries), len(merged)


# ----------------------------------------------------------------------------------------------
# List of popes
# ----------------------------------------------------------------------------------------------
MARKS = {'–': '--', '—': '---', '†': '\\textdagger{}', '‡': '\\textdaggerdbl{}', '§': '\\S{}',
         '’': "'", '‘': '`', '“': '``', '”': "''"}


def tex(s):
    for a, b in MARKS.items():
        s = s.replace(a, b)
    s = re.sub(r'\{\}$', '', s)                    # "Gregory I\textdagger{}" -> "Gregory I\textdagger"
    if any(ord(c) > 127 for c in s):
        raise ValueError('character without a TeX form in %r' % s)
    return s


def build_popes():
    src = open(os.path.join(ROOT, 'latex', 'backmatter', 'popes.tex'), encoding='utf-8').read()
    intro = re.search(r'\\popesintro\{([^}]*)\}', src).group(1).strip()
    popes = re.findall(r'\\pope\{([^}]*)\}\{([^}]*)\}', src)
    legend = re.search(r'\\begin\{popelegend\}(.*?)\\end\{popelegend\}', src, flags=re.S).group(1)
    legend = [x.strip() for x in legend.replace('{}', '').split('\\\\') if x.strip()]
    lines = [
        '% Generated by tools/summary_extras.py from latex/backmatter/popes.tex (the list of the book).',
        '% Do not edit.',
        '\\backchapter{List of Popes from Leo I to the Present}',
        '',
        '\\noindent The book closes with this list, which is given here in full and unchanged: %d names with'
        % len(popes),
        'their years in office, the antipopes among them. ' + tex(intro),
        '',
        '\\begin{popecolumns}',
    ]
    lines += ['\\pope{%s}{%s}' % (tex(d), tex(n)) for d, n in popes]
    lines += ['\\end{popecolumns}', '', '\\begin{popelegend}']
    lines += ['\\popemark %s' % tex(x) for x in legend]
    lines += ['\\end{popelegend}', '']
    return '\n'.join(lines), len(popes)


def main():
    check = '--check' in sys.argv
    chron, n_kd, n_lines = build_chronology()
    popes, n_popes = build_popes()
    stale = 0
    for name, new in (('chronology.tex', chron), ('popes.tex', popes)):
        path = os.path.join(BACK, name)
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if check:
            state = 'up to date' if old == new else ('MISSING' if old is None else 'OUT OF DATE')
            stale += old != new
            print('%-16s %s' % (name, state))
        else:
            os.makedirs(BACK, exist_ok=True)
            with open(path, 'w', encoding='utf-8') as f:
                f.write(new)
            print('%-16s written' % name)
    print('chronology: %d dated events from the chapters, %d entries; popes: %d' % (n_kd, n_lines, n_popes))
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
